// 댓글 기본 욕설 확인 (라우트 아님). 띄어쓰기·특수문자로 피해 쓰는 것도 어느 정도 잡도록 글자만 남겨 비교한다.
// 목록은 최소한이며, 걸리지 않은 나쁜 말은 신고와 관리자 검토로 거른다.
// 아이들의 일상 표현과 겹치는 말(예: 새끼 고양이, 씹다, 걸레, 불이 꺼져)은 넣지 않는다.
const WORDS = [
  '씨발', '시발', '씨팔', '시팔', 'ㅅㅂ', 'ㅆㅂ', '좆', '존나', '졸라', '병신', 'ㅂㅅ', '븅신', '지랄', 'ㅈㄹ',
  '개새끼', '개색기', '미친놈', '미친년', '닥쳐', '엠창', '느금', '니애미', '니애비', '창녀',
  'fuck', 'shit', 'bitch', 'asshole', 'nigger', 'retard',
];
// 욕설과 글자가 겹치는 보통 낱말 (먼저 지우고 검사)
const ALLOW = ['시발점', '시발역', '시발택시', '졸라매', '졸라맸', '졸라맨'];
export function hasBadWord(text) {
  let t = String(text || '').toLowerCase().replace(/[\s\d!-/:-@[-`{-~·•…ㆍ_*^]+/g, '');
  for (const a of ALLOW) t = t.split(a).join('');
  return WORDS.some(w => t.includes(w));
}
